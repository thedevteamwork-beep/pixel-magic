function variations(items: readonly TemplateItem[], names: readonly string[]): TemplateItem[] {
  return names.map((title, index) => ({
    ...items[index],
    id: `${items[index].id}-alternate`,
    title,
    filter: index % 3 === 0 ? "sepia(.2)" : items[index].filter,
  }));
}

